-- ====================================================================
-- SUPABASE MIGRATION: BẢNG NOTES (SỔ TAY GHI CHÚ ĐA NĂNG)
-- Hỗ trợ 4 loại: vocab, sentence, feedback, free
-- ====================================================================

-- 1. Tạo bảng notes nếu chưa có
CREATE TABLE IF NOT EXISTS public.notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid TEXT NOT NULL UNIQUE,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    type TEXT NOT NULL,                     -- vocab | sentence | feedback | free
    source TEXT NOT NULL,                   -- reading | listening | writing | speaking | camera | vocab_learning | ai_grading | manual
    source_ref TEXT,                        -- JSON hoặc id bài học, đề bài tham chiếu
    title TEXT NOT NULL,                    -- Tiêu đề từ vựng / câu / feedback tóm tắt
    content TEXT NOT NULL,                  -- Định nghĩa, nguyên văn câu, nhận xét chi tiết
    user_note TEXT,                         -- Ghi chú bổ sung do người học tự viết
    tags JSONB DEFAULT '[]'::jsonb,         -- Nhãn phân loại (VD: ["Band 7.5", "Topic Work"])
    color INTEGER,                          -- Màu thẻ highlight ghi chú (nếu có)
    is_pinned BOOLEAN DEFAULT FALSE,        -- Ghim lên đầu sổ tay
    vocab_data JSONB,                       -- Dữ liệu đầy đủ nếu là từ vựng (ipa, translation, example...)
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    deleted_at TIMESTAMPTZ                  -- Soft delete (NULL là còn hiệu lực)
);

-- 2. Đánh Index để tối ưu truy vấn
CREATE INDEX IF NOT EXISTS idx_notes_user_type ON public.notes(user_id, type);
CREATE INDEX IF NOT EXISTS idx_notes_uuid ON public.notes(uuid);
CREATE INDEX IF NOT EXISTS idx_notes_deleted ON public.notes(deleted_at);
CREATE INDEX IF NOT EXISTS idx_notes_pinned_updated ON public.notes(user_id, is_pinned DESC, updated_at DESC);

-- 3. Kích hoạt Row Level Security (RLS)
ALTER TABLE public.notes ENABLE ROW LEVEL SECURITY;

-- 4. Chính sách bảo mật RLS: Mỗi người dùng chỉ đọc và ghi chú của chính họ
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'notes' AND policyname = 'Users can view their own notes'
    ) THEN
        CREATE POLICY "Users can view their own notes" 
        ON public.notes FOR SELECT 
        USING (auth.uid() = user_id OR user_id IN (SELECT id FROM public.profiles WHERE username = 'learner'));
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'notes' AND policyname = 'Users can insert their own notes'
    ) THEN
        CREATE POLICY "Users can insert their own notes" 
        ON public.notes FOR INSERT 
        WITH CHECK (auth.uid() = user_id OR user_id IN (SELECT id FROM public.profiles WHERE username = 'learner'));
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'notes' AND policyname = 'Users can update their own notes'
    ) THEN
        CREATE POLICY "Users can update their own notes" 
        ON public.notes FOR UPDATE 
        USING (auth.uid() = user_id OR user_id IN (SELECT id FROM public.profiles WHERE username = 'learner'));
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'notes' AND policyname = 'Users can delete their own notes'
    ) THEN
        CREATE POLICY "Users can delete their own notes" 
        ON public.notes FOR DELETE 
        USING (auth.uid() = user_id OR user_id IN (SELECT id FROM public.profiles WHERE username = 'learner'));
    END IF;
END $$;

